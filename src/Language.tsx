const orderedTranslations = Object.entries(translations).sort(
  ([left], [right]) => right.length - left.length
);

function translateText(value: string): string {
  let translated = value;
  for (const [source, target] of orderedTranslations) {
    const escapedSource = source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const matcher = new RegExp(`(^|[^\\p{L}\\p{N}])${escapedSource}(?=$|[^\\p{L}\\p{N}])`, 'gu');
    translated = translated.replace(matcher, (_match, prefix: string) => `${prefix}${target}`);
  }
  return translated;
}

function translateNode(node: React.ReactNode): React.ReactNode {
  if (typeof node === 'string') return translateText(node);
  if (Array.isArray(node)) return node.map(translateNode);
  if (!React.isValidElement<{ children?: React.ReactNode }>(node)) return node;

  const props: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node.props)) {
    props[key] =
      typeof value === 'string' && ['placeholder', 'title', 'aria-label'].includes(key)
        ? translateText(value)
        : key === 'children'
          ? translateNode(value)
          : value;
  }

  return React.cloneElement(node, props);
}

export const TranslationBoundary: React.FC<{
  language: Language;
  children: React.ReactNode;
}> = ({ language, children }) => (
  <>
    {language === 'en' ? translateNode(children) : children}
  </>
);
